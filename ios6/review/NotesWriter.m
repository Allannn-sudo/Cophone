static void fail(NSError **error,NSString *message) {
    if(error)*error=[NSError errorWithDomain:@"CoPhoneReview" code:1 userInfo:@{NSLocalizedDescriptionKey:message}];
}
static BOOL backupNotes(NSError **error) {
    NSString *folder=@"/var/mobile/Library/CoPhoneReview/Backups";
    NSFileManager *fm=[NSFileManager defaultManager];
    if(![fm createDirectoryAtPath:folder withIntermediateDirectories:YES attributes:@{NSFilePosixPermissions:@0700} error:error])return NO;
    NSString *path=[folder stringByAppendingPathComponent:[NSString stringWithFormat:@"notes-%.0f.sqlite",[[NSDate date] timeIntervalSince1970]]];
    sqlite3 *source=NULL,*target=NULL;BOOL okay=NO;
    if(sqlite3_open_v2("/var/mobile/Library/Notes/notes.sqlite",&source,SQLITE_OPEN_READONLY,NULL)==SQLITE_OK
        && sqlite3_open_v2(path.UTF8String,&target,SQLITE_OPEN_READWRITE|SQLITE_OPEN_CREATE,NULL)==SQLITE_OK) {
        sqlite3_backup *copy=sqlite3_backup_init(target,"main",source,"main");
        if(copy){okay=sqlite3_backup_step(copy,-1)==SQLITE_DONE;okay=sqlite3_backup_finish(copy)==SQLITE_OK && okay;}
    }
    sqlite3_close(target);sqlite3_close(source);
    if(!okay){[fm removeItemAtPath:path error:NULL];fail(error,@"备忘录备份未完成，未尝试写入。");return NO;}
    [fm setAttributes:@{NSFilePosixPermissions:@0600} ofItemAtPath:path error:NULL];
    // Only prune files generated by this service, after a successful new backup.
    NSArray *files=[[[fm contentsOfDirectoryAtPath:folder error:NULL] filteredArrayUsingPredicate:[NSPredicate predicateWithFormat:@"SELF BEGINSWITH 'notes-' AND SELF ENDSWITH '.sqlite'"]] sortedArrayUsingSelector:@selector(compare:)];
    for(NSUInteger i=0;i+3<files.count;i++)[fm removeItemAtPath:[folder stringByAppendingPathComponent:[files objectAtIndex:i]] error:NULL];
    return YES;
}
static NSDictionary *readOwnNote(NSString *identifier) {
    sqlite3 *db=NULL;NSDictionary *value=nil;
    if(sqlite3_open_v2("/var/mobile/Library/Notes/notes.sqlite",&db,SQLITE_OPEN_READONLY,NULL)==SQLITE_OK) {
        sqlite3_stmt *statement=NULL;
        if(sqlite3_prepare_v2(db,"SELECT b.ZCONTENT,n.ZTITLE,n.ZINTEGERID FROM ZNOTE n JOIN ZNOTEBODY b ON n.ZBODY=b.Z_PK WHERE n.ZGUID=? AND COALESCE(n.ZDELETEDFLAG,0)=0",-1,&statement,NULL)==SQLITE_OK) {
            sqlite3_bind_text(statement,1,identifier.UTF8String,-1,SQLITE_TRANSIENT);
            if(sqlite3_step(statement)==SQLITE_ROW) {
                const unsigned char *text=sqlite3_column_text(statement,0);
                const unsigned char *title=sqlite3_column_text(statement,1);
                NSNumber *recordID=@(sqlite3_column_int64(statement,2));NSString *link=CophoneNoteResultURL(recordID);
                if(text && link)value=@{@"body":[NSString stringWithUTF8String:(const char *)text],@"title":title?[NSString stringWithUTF8String:(const char *)title]:@"",@"recordID":recordID,@"resultURL":link};
            }
        }
        sqlite3_finalize(statement);
    }
    sqlite3_close(db);return value;
}
NSString *CophoneSavedNoteURL(NSString *identifier){
    if(![identifier isKindOfClass:NSString.class] || ![[NSUUID alloc] initWithUUIDString:identifier])return nil;
    return readOwnNote(identifier)[@"resultURL"];
}
