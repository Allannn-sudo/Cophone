static BOOL ScheduleTaskNotification(NSString *message,NSString *action,NSString *resultURL,NSTimeInterval delay,NSError **error) {
    @try {
        dlopen("/System/Library/PrivateFrameworks/SpringBoardServices.framework/SpringBoardServices",RTLD_NOW);
        Class cls=NSClassFromString(@"SBSLocalNotificationClient");
        SEL schedule=@selector(scheduleLocalNotification:bundleIdentifier:waitUntilDone:);
        if(!cls || ![cls respondsToSelector:schedule] || ![cls respondsToSelector:@selector(scheduledLocalNotificationsForBundleIdentifier:)]){fail(error,@"本机通知接口不可用；备忘录已保存，请手动打开查看。");return NO;}
        UILocalNotification *notification=[[UILocalNotification alloc] init];
        notification.fireDate=[NSDate dateWithTimeIntervalSinceNow:delay];notification.timeZone=[NSTimeZone localTimeZone];
        notification.alertBody=message;
        notification.alertAction=@"查看";notification.applicationIconBadgeNumber=0;
        NSString *delivery=[[NSUUID UUID] UUIDString];
        // Keep older App fallback on its records tab if the optional route hook
        // is not loaded. Only verified photo completions get this marker.
        NSMutableDictionary *info=[[action isEqual:@"open-photos"]?@{@"CoPhoneAction":@"show-result",@"CoPhoneResultDestination":@"photos",@"CoPhoneDeliveryID":delivery}:@{@"CoPhoneAction":action,@"CoPhoneDeliveryID":delivery} mutableCopy];
        NSString *target=[action isEqual:@"open-notes"]?@"com.apple.mobilenotes":([action isEqual:@"open-photos"]?@"com.apple.mobileslideshow":nil);
        if(CophoneValidatedResultURL(resultURL,target))info[@"CoPhoneResultURL"]=resultURL;
        notification.userInfo=info;
        // The registered CoPhone app owns this local notification; no APNs or cloud involved.
        [cls scheduleLocalNotification:notification bundleIdentifier:@"ai.whaletech.cophone.classic" waitUntilDone:YES];
        for(UILocalNotification *pending in [cls scheduledLocalNotificationsForBundleIdentifier:@"ai.whaletech.cophone.classic"])
            if([pending.userInfo[@"CoPhoneDeliveryID"] isEqual:delivery]){if(target)CophoneMarkResultBadge(action);return YES;}
        fail(error,@"系统未确认接收完成通知；请手动查看备忘录。后台服务需要通知代理签名权限。");return NO;
    } @catch(NSException *exception) {fail(error,@"系统通知调用失败；请手动打开备忘录查看。");return NO;}
}

BOOL SendTaskNotification(NSString *message,NSString *action,NSError **error) {
    return ScheduleTaskNotification(message,action,nil,1.0,error);
}
BOOL SendTaskResultNotification(NSString *message,NSString *action,NSString *resultURL,NSError **error) {
    return ScheduleTaskNotification(message,action,resultURL,1.0,error);
}
BOOL SendTaskProgressNotification(NSString *message,NSError **error) {
    // Allow the Safari confirmation sheet to dismiss, then deliver promptly.
    return ScheduleTaskNotification(message,@"show-result",nil,0.75,error);
}
