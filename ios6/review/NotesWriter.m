NSDictionary *WriteNamedNote(NSString *identifier,NSString *text,NSString *prefix,NSError **error) {
    @try {
        NSDictionary *saved=readOwnNote(identifier);NSString *existing=saved[@"body"];
        if(existing) {
            if([existing isEqual:text])return @{@"guid":identifier,@"title":saved[@"title"],@"recordID":saved[@"recordID"],@"resultURL":saved[@"resultURL"],@"verified":@YES,@"reused":@YES,@"store":@"本机备忘录"};
            fail(error,@"同一轮备忘录已存在，但正文不符；不覆盖用户修改。");return nil;
        }
        void *framework=dlopen("/System/Library/PrivateFrameworks/Notes.framework/Notes",RTLD_NOW);
        Class cls=framework?NSClassFromString(@"NoteContext"):Nil;
        if(!cls || ![cls instancesRespondToSelector:@selector(newlyAddedNote)] || ![cls instancesRespondToSelector:@selector(saveOutsideApp:)]) {
            fail(error,@"本机 Notes 内部接口不兼容，未写入。");return nil;
        }
        if(!backupNotes(error))return nil;
        id context=[[cls alloc] init];
        if(![[[context rootDirectory] stringByStandardizingPath] isEqual:@"/var/mobile/Library/Notes"]) {
            fail(error,@"备忘录上下文路径不是 mobile 用户的 Notes，已停止。");return nil;
        }
        id local=[context localStore];if(!local){fail(error,@"没有本机备忘录存储；不改写云端账户。");return nil;}
        NSManagedObject *note=[context newlyAddedNote];
        if(!note){fail(error,@"系统未创建备忘录对象。");return nil;}
        NSDictionary *attributes=note.entity.attributesByName;
        for(NSString *key in @[@"guid",@"title",@"summary",@"creationDate",@"modificationDate"])
            if(![attributes objectForKey:key]){fail(error,[NSString stringWithFormat:@"备忘录属性不兼容：%@",key]);return nil;}
        NSString *title=CophoneNoteTitle(prefix,CophoneNoteTitle(text,@"本轮整理内容"));
        [note setValue:identifier forKey:@"guid"];[note setValue:title forKey:@"title"];
        [note setValue:CophoneNotePreview(text) forKey:@"summary"];
        [note setValue:[NSDate date] forKey:@"creationDate"];[note setValue:[NSDate date] forKey:@"modificationDate"];
        [note setValue:local forKey:@"store"];
        [note setIsPlainText:YES];[note setContent:text];
        if(![context saveOutsideApp:error])return nil;
        // Independently verify this UUID's title as well as its body.
        NSDictionary *readback=readOwnNote(identifier);
        if(![readback[@"title"] isEqual:title] || ![[readback[@"body"] stringByReplacingOccurrencesOfString:@"\r\n" withString:@"\n"] isEqual:[text stringByReplacingOccurrencesOfString:@"\r\n" withString:@"\n"]]) {
            fail(error,@"已调用系统保存，但独立回读标题或正文未匹配；不重复创建、不发送成功通知。");return nil;
        }
        return @{@"guid":identifier,@"title":title,@"recordID":readback[@"recordID"],@"resultURL":readback[@"resultURL"],@"verified":@YES,@"verifiedAt":@([[NSDate date] timeIntervalSince1970]),@"store":@"本机备忘录"};
    } @catch(NSException *exception) {
        fail(error,[NSString stringWithFormat:@"Notes 接口异常：%@；不自动重放。",exception.name]);return nil;
    }
}
